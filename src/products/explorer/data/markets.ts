function hydrateMarket(seed: MarketSeed): Market {
  const collateralSymbol = collateralSymbolFor(seed.chainId, seed.parent?.parentToken);
  const outcomes = seed.outcomes.map((outcome) => ({
    ...outcome,
    color: outcomeTone(outcome.name, seed.outcomes.indexOf(outcome)),
    wrappedToken: outcome.wrappedToken ?? `sample:wrapped:${seed.slug}:${outcome.id}`,
    tokenSymbol: outcome.tokenSymbol ?? outcome.id.replace(/[^a-z0-9]/gi, '').slice(0, 10).toUpperCase(),
    invalidValue: outcome.id === 'invalid' ? outcome.price : outcome.invalidValue,
  }));
  const activeOutcomes = outcomes.filter((outcome) => outcome.id !== 'estimate');
  const reward = rewardData[seed.id];
  const sampleMetrics = getSampleMetrics(seed);
  return {
    ...seed,
    outcomes,
    hasPriceHistory: seed.id !== 'market-conditional-ai-grant',
    marketState: marketStates[seed.id] ?? (seed.status === 'resolved' ? 'closed' : 'reports-not-open'),
    openingDate: openingDates[seed.id] ?? seed.createdAt,
    ...sampleMetrics,
    collateralSymbol,
    hasRewards: Boolean(reward),
    reward,
    resolutionOpensAt: `${seed.endDate}T14:00:00Z`,
    identity: getSampleIdentity(seed),
    provenance: getSampleProvenance(),
    oracle: getSampleOracle(seed),
    pool: {
      id: `sample:pool:${seed.slug}`,
      source: 'illustrative-fixture',
      collateralSymbol,
      lastPrice: outcomes[0]?.price ?? 0.5,
      ticks: [-0.02, -0.01, 0, 0.01, 0.02],
      balances: activeOutcomes.map((outcome, index) => ({
        outcomeId: outcome.id,
        shares: Math.round(seed.liquidity * Math.max(0.08, 0.42 - index * 0.035)),
        collateral: Math.round(seed.liquidity * Math.min(0.42, 0.28 + index * 0.018)),
      })),
    },
  };
}

