import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ entryPoints: ['src/products/explorer/data/positionBalances.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { readPositionBalances, completeSetBalance, exactTokenUnits } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const account = `0x${'1'.repeat(40)}`;
const token = `0x${'2'.repeat(40)}`;
const collateralToken = `0x${'4'.repeat(40)}`;
const market = { collateralAddress: collateralToken, chainId: 100, provenance: { origin: 'captured-api' }, outcomes: [{ id: 'yes', wrappedToken: token }, { id: 'no', wrappedToken: `0x${'3'.repeat(40)}` }] };
const word = (n) => `0x${BigInt(n).toString(16).padStart(64, '0')}`;
const calls = [];
const provider = { async request(args) {
  calls.push(args);
  if (args.method === 'eth_accounts') return [account];
  if (args.method === 'eth_chainId') return '0x64';
  if (args.method === 'eth_blockNumber') return '0xabc';
  if (args.method === 'eth_call') return args.params[0].data === '0x313ce567' ? word(18) : word(1234567890123456789n);
  throw new Error('Unexpected method');
} };
const snapshot = await readPositionBalances(provider, market, account);
assert.equal(snapshot.block, '0xabc');
assert.equal(snapshot.collateral.address, collateralToken);
assert.equal(exactTokenUnits(snapshot.collateral.raw, snapshot.collateral.decimals), '1.234567890123456789');
assert.ok(calls.some((call) => call.method === 'eth_call' && call.params[0].to === collateralToken));
assert.equal(completeSetBalance(snapshot.holdings), '1.234567890123456789');
assert.ok(calls.filter((call) => call.method === 'eth_call').every((call) => call.params[1] === '0xabc'));
assert.ok(calls.every((call) => !/send|sign|requestAccounts/i.test(call.method)));
assert.equal(exactTokenUnits(2n ** 200n, 18), '1606938044258990275541962092341162602522202.993782792835301376');
assert.equal(completeSetBalance([{ raw: 150n, decimals: 2 }, { raw: 1400000n, decimals: 6 }]), '1.4');
assert.equal(completeSetBalance([{ raw: 0n, decimals: 18 }]), '0');
assert.equal(completeSetBalance([{ raw: null, decimals: null }]), null);
assert.equal(completeSetBalance([]), null);
const partial = await readPositionBalances({ request: (args) => args.method === 'eth_call' && args.params[0].to === token ? Promise.reject(new Error('Offline')) : provider.request(args) }, market, account);
assert.equal(partial.holdings[0].raw, null);
assert.equal(completeSetBalance(partial.holdings), null);
await assert.rejects(() => readPositionBalances({ request: (args) => args.method === 'eth_chainId' ? Promise.resolve('0x1') : provider.request(args) }, market, account), /network/);
let reads = 0;
await assert.rejects(() => readPositionBalances({ request: (args) => args.method === 'eth_accounts' ? Promise.resolve([++reads > 1 ? token : account]) : provider.request(args) }, market, account), /account changed/);
await assert.rejects(() => readPositionBalances(provider, { ...market, provenance: { origin: 'illustrative-fixture' } }, account), /captured market/);
console.log('Position checks passed: precision, fixed block, partial failure, chain/account changes, read-only methods.');

const collateralFailure = await readPositionBalances({ request: (args) => args.method === 'eth_call' && args.params[0].to === collateralToken ? Promise.reject(new Error('Unavailable')) : provider.request(args) }, market, account);
assert.equal(collateralFailure.collateral.raw, null);
assert.equal(completeSetBalance(collateralFailure.holdings), '1.234567890123456789');
const absentCollateral = await readPositionBalances(provider, { ...market, collateralAddress: undefined }, account);
assert.equal(absentCollateral.collateral.raw, null);
const mixedPrecision = await readPositionBalances({ request: (args) => args.method === 'eth_call' && args.params[0].to === collateralToken ? Promise.resolve(args.params[0].data === '0x313ce567' ? word(6) : word(1234567)) : provider.request(args) }, market, account);
assert.equal(exactTokenUnits(mixedPrecision.collateral.raw, mixedPrecision.collateral.decimals), '1.234567');
console.log('Collateral checks passed: fixed-block contract reads, independent failure, missing contract, mixed precision.');
