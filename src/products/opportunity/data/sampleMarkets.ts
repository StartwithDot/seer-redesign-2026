export function sampleMarketsForCount(raw: string | null): MarketRecord[] {
  if (raw === null || !/^\d+$/.test(raw)) return deterministicSampleMarkets;
  const count = Math.min(12, Math.max(1, Number(raw)));
  const catalogue = [...deterministicSampleMarkets];
  for (let i = catalogue.length; i < 12; i += 1) {
    const base = deterministicSampleMarkets[i - deterministicSampleMarkets.length];
    catalogue.push({ ...base, id: `sample-workspace-${i + 1}`, title: `Sample workspace ${i + 1}: ${base.title}`, creator: `Sample operator ${i + 1}`, contract: null });
  }
  return catalogue.slice(0, count);
}
